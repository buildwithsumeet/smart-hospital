import { AuthService } from '../../services/auth-service/src/services/auth.service';
import { UserRepository } from '../../services/auth-service/src/repositories/user.repository';
import { seedDefaultUsers } from '../../services/auth-service/src/database/seeds/seed-users';
import { DoctorService } from '../../services/doctor-service/src/services/doctor.service';
import { DoctorRepository } from '../../services/doctor-service/src/repositories/doctor.repository';
import { seedDefaultDoctorsAndDepartments } from '../../services/doctor-service/src/database/seeds/seed-doctors';
import { AppointmentService } from '../../services/appointment-service/src/services/appointment.service';
import { AppointmentRepository } from '../../services/appointment-service/src/repositories/appointment.repository';
import { BillingService } from '../../services/billing-service/src/services/billing.service';
import { BillingRepository } from '../../services/billing-service/src/repositories/billing.repository';
import { registerBillingEventConsumers } from '../../services/billing-service/src/messaging/billing-event-consumer';
import { NotificationService } from '../../services/notification-service/src/services/notification.service';
import { NotificationRepository } from '../../services/notification-service/src/repositories/notification.repository';
import { registerNotificationEventConsumers } from '../../services/notification-service/src/messaging/notification-event-consumer';
import { EventBus, UserRole, AppointmentStatus, PaymentMethod, InvoiceStatus } from '@hospital/common';

describe('E2E Clinical & Healthcare Lifecycle Workflow', () => {
  const eventBus = EventBus.getInstance();
  let patientUser: any;
  let doctorUser: any;
  let doctorProfile: any;
  let bookedAppointment: any;
  let generatedInvoice: any;

  beforeAll(async () => {
    // Configure in-memory repositories for pure e2e logic isolation
    UserRepository.setUseMemory(true);
    DoctorRepository.setUseMemory(true);
    AppointmentRepository.setUseMemory(true);
    BillingRepository.setUseMemory(true);
    NotificationRepository.setUseMemory(true);

    // Register event listeners across domains
    await registerBillingEventConsumers(eventBus);
    await registerNotificationEventConsumers(eventBus);

    // Seed defaults
    await seedDefaultUsers();
    await seedDefaultDoctorsAndDepartments();

    const doctors = await DoctorService.listDoctors({});
    doctorProfile = doctors[0];
  });

  afterAll(async () => {
    UserRepository.clearMemory();
    DoctorRepository.clearMemory();
    AppointmentRepository.clearMemory();
    BillingRepository.clearMemory();
    NotificationRepository.clearMemory();
  });

  it('Step 1: Patient logs into platform', async () => {
    const loginResult = await AuthService.login({
      email: 'patient@hospital.com',
      password: 'Patient@12345'
    });

    expect(loginResult.user.email).toBe('patient@hospital.com');
    expect(loginResult.tokens.accessToken).toBeDefined();
    patientUser = loginResult.user;
  });

  it('Step 2: Patient searches for Cardiologists & queries available time slots', async () => {
    const doctors = await DoctorService.listDoctors({ specialization: 'Cardiologist' });
    expect(doctors.length).toBeGreaterThanOrEqual(1);

    // 2026-11-24 is a Tuesday (active schedule)
    const slots = await DoctorService.getAvailableSlots(doctors[0].id, '2026-11-24');
    expect(slots.length).toBeGreaterThanOrEqual(10);
    expect(slots[0].startTime).toBe('09:00');
  });

  it('Step 3: Patient books an appointment slot (validated against double booking)', async () => {
    bookedAppointment = await AppointmentService.bookAppointment({
      patientId: patientUser.id,
      doctorId: doctorProfile.id,
      appointmentDate: '2026-11-24',
      startTime: '09:00',
      endTime: '09:30',
      consultationFee: doctorProfile.consultationFee,
      reason: 'Routine ECG and cardiac checkup'
    });

    expect(bookedAppointment.id).toBeDefined();
    expect(bookedAppointment.status).toBe(AppointmentStatus.PENDING);
  });

  it('Step 4: Asynchronous events trigger Billing Invoice Generation & Confirmation Notification', async () => {
    // Wait briefly for asynchronous RabbitMQ event bus handlers
    await new Promise((resolve) => setTimeout(resolve, 50));

    // Verify Invoice was generated by Billing Service
    const invoices = await BillingService.listInvoices({ patientId: patientUser.id });
    expect(invoices.length).toBeGreaterThanOrEqual(1);
    generatedInvoice = invoices[0];
    expect(Number(generatedInvoice.totalAmount)).toBe(doctorProfile.consultationFee);
    expect(generatedInvoice.status).toBe(InvoiceStatus.PENDING);

    // Verify Confirmation Email Notification was dispatched
    const notifications = await NotificationService.listNotifications({
      notificationType: 'APPOINTMENT_CONFIRMED'
    });
    expect(notifications.length).toBeGreaterThanOrEqual(1);
    expect(notifications[0].subject).toContain('Appointment Confirmed');
  });

  it('Step 5: Doctor views appointment & progresses clinical visit status to COMPLETED', async () => {
    // Check-In
    await AppointmentService.updateStatus(
      bookedAppointment.id,
      AppointmentStatus.CHECKED_IN,
      'Reception Desk'
    );

    // In Consultation
    await AppointmentService.updateStatus(
      bookedAppointment.id,
      AppointmentStatus.IN_CONSULTATION,
      'Dr. Sarah Jenkins'
    );

    // Complete consultation with notes
    const completed = await AppointmentService.updateStatus(
      bookedAppointment.id,
      AppointmentStatus.COMPLETED,
      'Dr. Sarah Jenkins',
      'Normal sinus rhythm. Prescribed multivitamins.'
    );

    expect(completed.status).toBe(AppointmentStatus.COMPLETED);
    expect(completed.notes).toContain('Normal sinus rhythm');
  });

  it('Step 6: Patient processes payment via Mock Payment Gateway', async () => {
    const paymentResult = await BillingService.processPayment({
      invoiceId: generatedInvoice.id,
      patientId: patientUser.id,
      amount: generatedInvoice.totalAmount,
      paymentMethod: PaymentMethod.CREDIT_CARD
    });

    expect(paymentResult.invoice.status).toBe(InvoiceStatus.PAID);
    expect(paymentResult.payment.status).toBe('SUCCESS');
    expect(paymentResult.payment.transactionRef).toMatch(/^TXN-/);

    // Wait for payment receipt notification
    await new Promise((resolve) => setTimeout(resolve, 50));
    const receipts = await NotificationService.listNotifications({
      notificationType: 'PAYMENT_RECEIPT'
    });
    expect(receipts.length).toBeGreaterThanOrEqual(1);
  });

  it('Step 7: Accountant inspects revenue analytics & simulates refund', async () => {
    const analytics = await BillingService.getRevenueAnalytics();
    expect(analytics.totalRevenue).toBeGreaterThanOrEqual(doctorProfile.consultationFee);
    expect(analytics.paidInvoicesCount).toBeGreaterThanOrEqual(1);

    // Simulating refund
    const payments = await BillingRepository.findPaymentById((await BillingRepository.findPaymentById('any'))?.id || '');
    // Process refund directly
    const refund = await BillingRepository.createRefund({
      paymentId: 'test-payment-id',
      invoiceId: generatedInvoice.id,
      amount: generatedInvoice.totalAmount,
      reason: 'Administrative dispute resolution'
    });

    expect(refund.refundRef).toMatch(/^REF-/);
  });
});
